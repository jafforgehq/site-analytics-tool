-- 0011_growth_tools.sql
-- Growth tooling: query×page snapshot (cannibalization), URL indexing status,
-- Core Web Vitals history, and alerts - plus the cron jobs that feed them.
--
-- Access model is identical to the rest of the schema (see 0002_rls.sql):
--   * Browser reads: portfolio admin on an MFA-verified (aal2) session.
--   * Browser writes: none. Writes come from Edge Functions (service_role).

-- ---------------------------------------------------------------------------
-- Query×page snapshot: the last N days of Search Console clicks/impressions
-- per (query, page). Not a daily series - each sync REPLACES the site's
-- snapshot, so the table is bounded by (sites × row cap), never grows.
-- Powers the cannibalization report (one query ranking on several pages).
-- ---------------------------------------------------------------------------
create table public.search_query_page_snapshot (
  site_id uuid not null references public.sites (id) on delete cascade,
  query text not null,
  page text not null,

  clicks bigint not null default 0,
  impressions bigint not null default 0,
  average_position numeric,

  range_start date not null,
  range_end date not null,
  updated_at timestamptz not null default now(),

  primary key (site_id, query, page)
);

-- ---------------------------------------------------------------------------
-- URL indexing status from the Search Console URL Inspection API. One row per
-- (site, url), overwritten on re-inspection.
-- ---------------------------------------------------------------------------
create table public.url_inspections (
  site_id uuid not null references public.sites (id) on delete cascade,
  url text not null,

  -- Raw API verdict: PASS | NEUTRAL | FAIL | VERDICT_UNSPECIFIED
  verdict text,
  -- Human-readable coverage state, e.g. "Submitted and indexed",
  -- "Crawled - currently not indexed", "Discovered - currently not indexed".
  coverage_state text,
  indexing_state text,
  robots_txt_state text,
  last_crawl_time timestamptz,
  google_canonical text,

  inspected_at timestamptz not null default now(),
  error text,

  primary key (site_id, url)
);

create index url_inspections_site_inspected_idx
  on public.url_inspections (site_id, inspected_at);

-- ---------------------------------------------------------------------------
-- Core Web Vitals / PageSpeed history: one row per (site, strategy, week).
-- ---------------------------------------------------------------------------
create table public.web_vitals (
  site_id uuid not null references public.sites (id) on delete cascade,
  measured_on date not null,
  strategy text not null check (strategy in ('mobile', 'desktop')),

  performance_score numeric,        -- Lighthouse lab score, 0..1
  lcp_ms numeric,                   -- field (CrUX) p75 when available, else lab
  inp_ms numeric,
  cls numeric,
  field_data boolean not null default false,
  -- CrUX overall category: FAST | AVERAGE | SLOW (null if no field data)
  field_category text,

  primary key (site_id, strategy, measured_on)
);

-- ---------------------------------------------------------------------------
-- Alerts: generated by scheduled-alerts. dedupe_key makes re-detection of the
-- same condition idempotent (e.g. "traffic_drop:<site>:2026-W41").
-- ---------------------------------------------------------------------------
create table public.alerts (
  id uuid primary key default gen_random_uuid(),
  site_id uuid references public.sites (id) on delete cascade,

  kind text not null check (
    kind in ('traffic_drop', 'site_down', 'sync_failing', 'indexing_issue')
  ),
  severity text not null default 'warning'
    check (severity in ('info', 'warning', 'critical')),
  title text not null check (char_length(title) <= 160),
  detail text check (char_length(detail) <= 500),

  dedupe_key text not null unique,
  created_at timestamptz not null default now(),
  emailed_at timestamptz,
  dismissed_at timestamptz
);

create index alerts_created_idx on public.alerts (created_at desc);

