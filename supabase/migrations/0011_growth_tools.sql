-- ---------------------------------------------------------------------------
-- Cron: same Vault-based pattern as 0005_cron_jobs.sql / 0009 (uptime).
--   scheduled-indexing  daily  05:00 UTC
--   scheduled-vitals    Mondays 05:15 UTC
--   scheduled-alerts    daily  05:30 UTC (after the 04:00 syncs finish)
-- ---------------------------------------------------------------------------
create or replace function public.invoke_edge_function(p_name text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_url text;
  v_secret text;
begin
  select decrypted_secret into v_url
  from vault.decrypted_secrets where name = 'project_url';
  select decrypted_secret into v_secret
  from vault.decrypted_secrets where name = 'automation_secret';

  if v_url is null or v_secret is null then
    raise exception 'Missing Vault secret project_url or automation_secret';
  end if;

  perform net.http_post(
    url := v_url || '/functions/v1/' || p_name,
    headers := jsonb_build_object(
      'Content-Type', 'application/json',
      'X-Automation-Secret', v_secret
    ),
    body := '{}'::jsonb,
    timeout_milliseconds := 60000
  );
end;
$$;

revoke all on function public.invoke_edge_function(text) from public;
revoke all on function public.invoke_edge_function(text) from anon, authenticated;

do $$
declare
  j text;
begin
  foreach j in array array[
    'site-analytics-indexing',
    'site-analytics-vitals',
    'site-analytics-alerts'
  ] loop
    if exists (select 1 from cron.job where jobname = j) then
      perform cron.unschedule(j);
    end if;
  end loop;
end;
$$;

select cron.schedule(
  'site-analytics-indexing', '0 5 * * *',
  $$select public.invoke_edge_function('scheduled-indexing')$$
);
select cron.schedule(
  'site-analytics-vitals', '15 5 * * 1',
  $$select public.invoke_edge_function('scheduled-vitals')$$
);
select cron.schedule(
  'site-analytics-alerts', '30 5 * * *',
  $$select public.invoke_edge_function('scheduled-alerts')$$
);

-- ---------------------------------------------------------------------------
-- Retention: extend the weekly cleanup so alerts and vitals stay bounded.
-- (url_inspections / the snapshot are overwritten in place and need none.)
-- ---------------------------------------------------------------------------
create or replace function public.prune_growth_data()
returns void
language sql
security definer
set search_path = ''
as $$
  delete from public.alerts where created_at < now() - interval '180 days';
  delete from public.web_vitals where measured_on < (now() - interval '540 days')::date;
$$;

revoke all on function public.prune_growth_data() from public;
revoke all on function public.prune_growth_data() from anon, authenticated;

do $$
begin
  if exists (select 1 from cron.job where jobname = 'site-analytics-growth-cleanup') then
    perform cron.unschedule('site-analytics-growth-cleanup');
  end if;
end;
$$;

select cron.schedule(
  'site-analytics-growth-cleanup', '35 3 * * 0',
  $$select public.prune_growth_data()$$
);
